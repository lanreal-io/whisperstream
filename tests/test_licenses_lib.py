def test_silero_notice_preserves_pinned_license_and_model_attribution():
    import hashlib
    from pathlib import Path
    from whisperstream.speech_gate import MODEL_PATH, MODEL_SHA256
    license_file = MODEL_PATH.with_name('silero-vad-LICENSE.txt')
    assert hashlib.sha256(license_file.read_bytes()).hexdigest() == '2e63e9a38b6e8fc0c7bc37ce174caca1862870856c6daf5697cfb785e925520b'
    assert hashlib.sha256(MODEL_PATH.read_bytes()).hexdigest() == MODEL_SHA256
    txt, rows = generator.TxtBuilder(), generator.Rows()
    generator._section8_silero(txt, rows)
    assert license_file.read_text(encoding='utf-8') in txt.text()
    assert MODEL_SHA256 in txt.text()
    assert rows.count_eco('Model') == 1
    for path in (generator.OUT_TXT, generator.OUT_STAGED):
        assert txt.text() in Path(path).read_text(encoding='utf-8')


