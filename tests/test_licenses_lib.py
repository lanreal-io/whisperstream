    def test_plain_package(self):
        name, version = lib.split_npm_key("lodash@4.17.21")
        assert name == "lodash"
        assert version == "4.17.21"

    def test_scoped_package(self):
        # @scope/name@1.2.3 -> name="@scope/name", version="1.2.3"
        name, version = lib.split_npm_key("@scope/name@1.2.3")
        assert name == "@scope/name"
        assert version == "1.2.3"

    def test_scoped_real_world(self):
        name, version = lib.split_npm_key("@radix-ui/react-dialog@1.0.5")
        assert name == "@radix-ui/react-dialog"
        assert version == "1.0.5"

    def test_scoped_deep_path(self):
        # e.g. "@babel/core@7.21.0"
        name, version = lib.split_npm_key("@babel/core@7.21.0")
        assert name == "@babel/core"
        assert version == "7.21.0"

    def test_plain_no_scope(self):
        name, version = lib.split_npm_key("react@18.2.0")
        assert name == "react"
        assert version == "18.2.0"


