class TestMdEscape:
    def test_no_pipes(self):
        assert lib.md_escape("hello world") == "hello world"

    def test_single_pipe(self):
        assert lib.md_escape("a|b") == r"a\|b"

    def test_multiple_pipes(self):
        assert lib.md_escape("a|b|c") == r"a\|b\|c"

    def test_empty(self):
        assert lib.md_escape("") == ""

    def test_already_escaped_escapes_again(self):
        # sed 's/|/\\|/g' replaces every | with \|, including a | that follows a backslash.
        # Input r"a\|b" has a literal backslash and a literal pipe; the pipe gets escaped
        # so the output is r"a\\|b" (the backslash is unchanged, the pipe gains a prefix).
        s = r"a\|b"
        # The pipe in the input becomes \| -- result is a\\ followed by \|.
        assert lib.md_escape(s) == "a" + "\\" + "\\|" + "b"


