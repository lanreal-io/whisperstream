SAMPLE_UV_EXPORT = """\
# This file was autogenerated by uv via the following command:
#    uv export --no-dev --no-hashes --no-emit-project --format requirements-txt
annotated-types==0.7.0
anyio==4.9.0
certifi==2025.1.31
  # via httpcore
PyYAML==6.0.2
python-dateutil==2.9.0.post0
pycaw==20181226
sherpa-onnx==1.10.35
"""

class TestRuntimeClosureFromUvExport:
    def test_basic(self):
        result = lib.runtime_closure_from_uv_export(SAMPLE_UV_EXPORT)
        # Lines starting with whitespace (comment continuation) or '#' are excluded.
        # The function must lower + dash->underscore normalize the names.
        assert "annotated_types" in result
        assert "anyio" in result
        assert "certifi" in result
        assert "pyyaml" in result
        assert "python_dateutil" in result
        assert "pycaw" in result
        assert "sherpa_onnx" in result

    def test_excludes_comment_lines(self):
        result = lib.runtime_closure_from_uv_export(SAMPLE_UV_EXPORT)
        # Lines starting with '#' should not appear
        for item in result:
            assert not item.startswith("#")

    def test_excludes_indented_lines(self):
        result = lib.runtime_closure_from_uv_export(SAMPLE_UV_EXPORT)
        # Lines starting with whitespace (like "  # via httpcore") should be excluded.
        # They would become empty strings or "via" -- neither should appear.
        for item in result:
            assert item.strip() == item

    def test_returns_set(self):
        result = lib.runtime_closure_from_uv_export(SAMPLE_UV_EXPORT)
        assert isinstance(result, set)

    def test_deduplication(self):
        # Duplicate packages should only appear once.
        text = "requests==2.0\nrequests==2.1\n"
        result = lib.runtime_closure_from_uv_export(text)
        assert result == {"requests"}

    def test_empty_text(self):
        result = lib.runtime_closure_from_uv_export("")
        assert result == set()


