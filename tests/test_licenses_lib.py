class TestClassifyFlag:
    def test_agpl(self):
        assert lib.classify_flag("AGPL-3.0") == "AGPL"

    def test_agpl_lowercase(self):
        # Bash does uppercase before matching, so lowercase input also matches.
        assert lib.classify_flag("agpl-3.0-only") == "AGPL"

    def test_lgpl(self):
        assert lib.classify_flag("LGPL-2.1-or-later") == "LGPL"

    def test_lgpl_lowercase(self):
        assert lib.classify_flag("lgpl-2.1") == "LGPL"

    def test_gpl_not_lgpl_or_agpl(self):
        # "GPL-2.0" contains GPL but not AGPL or LGPL.
        # Cascade: AGPL first, then LGPL, then GPL -- so pure GPL wins here.
        assert lib.classify_flag("GPL-2.0") == "GPL"

    def test_gpl_plain(self):
        assert lib.classify_flag("GPL-3.0-only") == "GPL"

    def test_mpl(self):
        assert lib.classify_flag("MPL-2.0") == "MPL"

    def test_mpl_lowercase(self):
        assert lib.classify_flag("mpl-2.0") == "MPL"

    def test_custom(self):
        assert lib.classify_flag("Custom") == "Custom"

    def test_custom_lowercase(self):
        assert lib.classify_flag("custom license") == "Custom"

    def test_mit_returns_empty(self):
        # MIT has no copyleft flag -- returns "".
        assert lib.classify_flag("MIT") == ""

    def test_apache_returns_empty(self):
        assert lib.classify_flag("Apache-2.0") == ""

    def test_bsd_returns_empty(self):
        assert lib.classify_flag("BSD-3-Clause") == ""

    def test_empty_string_returns_unknown(self):
        assert lib.classify_flag("") == "UNKNOWN"

    def test_unknown_literal_returns_unknown(self):
        assert lib.classify_flag("UNKNOWN") == "UNKNOWN"

    def test_unknown_lowercase_returns_unknown(self):
        assert lib.classify_flag("unknown") == "UNKNOWN"

    def test_agpl_takes_priority_over_gpl(self):
        # A string like "AGPL-3.0-or-later" contains AGPL (checked first), not just GPL.
        assert lib.classify_flag("AGPL-3.0-or-later") == "AGPL"

    def test_lgpl_takes_priority_over_gpl(self):
        # LGPL contains "GPL" as a substring, but LGPL is checked before GPL.
        result = lib.classify_flag("LGPL-2.1-only")
        assert result == "LGPL"


