"""Synthetic speech clip for tests that need a real spoken sentence.

The clip is generated by ``scripts/generate_speech_fixture.py`` with the
Kokoro voice model, so no real voice recording is involved. Audio files may be
absent from a checkout (the public projection drops audio it has not pinned);
every accessor then skips the calling test instead of failing.
"""

from __future__ import annotations

import wave
from pathlib import Path

import numpy as np
import pytest

SPEECH_DIR = Path(__file__).resolve().parent / "fixtures" / "synthetic"
SPEECH_WAV = SPEECH_DIR / "speech.wav"
SPEECH_TEXT = SPEECH_DIR / "speech.txt"


def require_fixture(path: Path) -> Path:
    """Return ``path`` or skip the calling test when the fixture is absent."""
    if not path.is_file():
        pytest.skip(f"audio fixture is not present in this checkout: {path.name}")
    return path


def speech_audio() -> tuple[np.ndarray, int]:
    """Return the clip as float32 mono samples and its sample rate."""
    with wave.open(str(require_fixture(SPEECH_WAV)), "rb") as wav:
        assert wav.getnchannels() == 1
        assert wav.getsampwidth() == 2
        sample_rate = wav.getframerate()
        frames = wav.readframes(wav.getnframes())
    return np.frombuffer(frames, dtype="<i2").astype(np.float32) / 32768.0, sample_rate


def speech_wav_bytes() -> bytes:
    return require_fixture(SPEECH_WAV).read_bytes()


def speech_text() -> str:
    """Return the sentence the clip speaks, as the STT engines transcribe it."""
    return require_fixture(SPEECH_TEXT).read_text(encoding="utf-8").strip()


# Apply to every test that uses the clip, so the skip happens at setup before
# the test starts any worker or server it would otherwise leave running.
requires_speech_fixture = pytest.mark.skipif(
    not (SPEECH_WAV.is_file() and SPEECH_TEXT.is_file()),
    reason="the synthetic speech fixture is not present in this checkout",
)
